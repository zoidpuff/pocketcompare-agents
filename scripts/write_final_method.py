#!/usr/bin/env python
"""Write configs/final_method.yaml (+ shipped input statistics) for the candidate chosen by the PREREG §1 selection.

    python scripts/write_final_method.py --selection results/dev/final_select_all_details.json

Non-learned: the BLiPS-train v2 part statistics go to results/models/final/<input>_input_stats.json.  A4b: the
model directory's input_stats.json and seed npz files are referenced in place.  Every referenced file is listed with
its sha256 (``pocketcompare.method.Method`` verifies them on load).
"""
from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from pocketcompare import a4b as A4  # noqa: E402
from pocketcompare import pockets as pk  # noqa: E402
from pocketcompare.descriptors import a1 as A1  # noqa: E402
from pocketcompare.descriptors import a1r as A1R  # noqa: E402
from pocketcompare.provenance import git_state, sha256_file  # noqa: E402


def rel(p) -> str:
    return str(Path(p).resolve().relative_to(ROOT))


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--selection", required=True)
    ap.add_argument("--out", default=str(ROOT / "configs/final_method.yaml"))
    a = ap.parse_args()
    import yaml
    det = json.loads(Path(a.selection).read_text())
    chosen = det["selection"]["chosen"]
    cand, variant = chosen.split("|")
    cands = {c["name"]: c for c in det["candidates"]}
    c = cands[cand]
    files = {}
    if c["kind"] == "nonlearned":
        stats = ROOT / "results/models/final" / f"{c['inp']}_input_stats.json"
        stats.parent.mkdir(parents=True, exist_ok=True)
        stats.write_text(json.dumps(A4.blips_train_scaler(c["inp"]).to_dict()))
        model_files = []
        dims = c["dims"]
    else:
        md = Path(c["model_dir"])
        mcfg = json.loads((md / "config.json").read_text())
        stats = md / "input_stats.json"
        model_files = [rel(md / f"seed{s}.npz") for s in mcfg["seeds"]]
        dims = mcfg["out_dim"] * len(mcfg["seeds"])
    for f in [rel(stats)] + model_files:
        files[f] = sha256_file(ROOT / f)
    a1cfg = A1.make_config()
    git = git_state()
    out = {
        "name": f"pocketcompare-final:{cand}|{variant}",
        "selected_by": rel(a.selection), "selection_rule": "PREREG §1 (one-SE rule on BLiPS-val D-mode cb-AUC + guards)",
        "kind": c["kind"], "candidate": cand, "variant": variant, "input": c["inp"], "dims": int(dims),
        "csls_k": 10, "csls_background": "the searched database (evaluation: the evaluated split's pocket pool)",
        "parts": [{"src": s, "shaper": sh} for s, sh in A4.PARTS[c["inp"]]],
        "site": {"L_cutoff_A": pk.L_CUTOFF, "residue_cutoff_A": pk.RES_CUTOFF, "residue_bur_min": pk.RES_BUR_MIN,
                 "D_pockets": "BURROW region-rule output (pk_in_region), each sub-pocket separately",
                 "D_locator_with_site": "best-covering region pocket (pockets.best_member, cover 1.5 Å)",
                 "shaper_sph8": {"radius_A": 8.0, "centroid": "vol * bur16^4-weighted", "bur_feature":
                                 pk.SITE_BUR_FEATURE, "bur_min": pk.SITE_BUR_MIN}},
        "a1": {"version": A1.A1_VERSION, "overrides": {}, "config_hash": A1.config_hash(a1cfg)},
        "env": {"version": A1R.A1R_VERSION, "dims": A1R.env_layout()[-1]["stop"]},
        "scaling": "per part z-score, BLiPS-train v2 sites (L + D rows), constant dims -> 0"
                   + ("; A4b input clipped to +-%g" % A4.CLIP if c["kind"] == "learned" else "; equal-weight block cosine"),
        "input_stats": rel(stats), "model_files": model_files, "files_sha256": files,
        "burrow": {"preset": "default", "ranker": "all", "region_rule": pk.REGION_RULE},
        "git_commit": git["git_commit"], "git_dirty": git["git_dirty"],
    }
    if c["kind"] == "learned":
        out["a4b"] = {k: mcfg[k] for k in ("name", "hidden", "out_dim", "dropout", "seeds", "d_in", "best_epochs")}
        out["a4b"]["config_json"] = rel(md / "config.json")
        files[rel(md / "config.json")] = sha256_file(md / "config.json")
    Path(a.out).write_text("# Final method (generated by scripts/write_final_method.py; do not edit by hand)\n"
                           + yaml.safe_dump(out, sort_keys=False, allow_unicode=True))
    print(Path(a.out).read_text())


if __name__ == "__main__":
    main()
